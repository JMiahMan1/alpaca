def _recipe(cue: dict[str, Any]) -> dict[str, Any]:
    return {"prompt": cue["prompt"], "duration_s": cue["duration_s"], "seed": cue["seed"], "loop": bool(cue["loop"])}


def is_current(name: str) -> bool:
    """The cue's file was composed from the recipe in ``CUES`` now (a changed prompt recomposes it)."""
    path = cue_path(name)
    if not path.is_file():
        return False
    try:
        return json.loads(path.with_suffix(".json").read_text()) == _recipe(CUES[name])
    except (OSError, ValueError):
        return False


_state: dict[str, Any] = {"thread": None, "last_attempt": 0.0, "errors": {}}
_lock = threading.Lock()


def cue_path(name: str) -> Path:
    return MUSIC_DIR / f"{name}.wav"


def manifest() -> dict[str, Any]:
    """What a stage or phone needs to play the music: which cues exist and how."""
    cues = {}
    for name, cue in CUES.items():
        path = cue_path(name)
        ready = path.is_file() and path.stat().st_size > 1024
        cues[name] = {
            "ready": ready,
            "loop": bool(cue["loop"]),
            "volume": float(cue["volume"]),
            "url": f"/api/party/music/{name}.wav?v={int(path.stat().st_mtime)}" if ready else None,
        }
    return {"cues": cues, "generating": bool(_state["thread"] and _state["thread"].is_alive()),
            "errors": dict(_state["errors"])}


# --------------------------------------------------------------------------- audio (pure, stdlib only)

def _read_wav(data: bytes) -> tuple[array.array, int, int]:
    """16-bit PCM samples (interleaved), sample rate, channels."""
    with wave.open(io.BytesIO(data)) as w:
        if w.getsampwidth() != 2:
            raise ValueError("expected 16-bit PCM")
        frames = w.readframes(w.getnframes())
        samples = array.array("h")
        samples.frombytes(frames)
        return samples, w.getframerate(), w.getnchannels()


def _to_mono(samples: array.array, channels: int) -> array.array:
    if channels == 1:
        return samples
    out = array.array("h", [0]) * (len(samples) // channels)
    for i in range(len(out)):
        out[i] = int(sum(samples[i * channels + c] for c in range(channels)) / channels)
    return out


def _resample(samples: array.array, src: int, dst: int) -> array.array:
    """Linear resample (a bed under speech does not need better)."""
    if src == dst or not samples:
        return samples
    n = int(len(samples) * dst / src)
    out = array.array("h", [0]) * n
    step = src / dst
    last = len(samples) - 1
    for i in range(n):
        x = i * step
        j = int(x)
        f = x - j
        a = samples[j]
        b = samples[j + 1] if j < last else a
        out[i] = int(a + (b - a) * f)
    return out


def make_loop(samples: array.array, rate: int, crossfade_s: float = LOOP_CROSSFADE_S) -> array.array:
    """Fold the tail into the head so the clip repeats with no seam.

    The last ``crossfade_s`` fades out over the first ``crossfade_s`` fading in,
    and the tail is dropped: played back to back, the end runs straight into
    the music it was blended with.
    """
    n = int(rate * crossfade_s)
    if n <= 0 or len(samples) < 3 * n:
        return samples
    body = array.array("h", samples[: len(samples) - n])
    tail = samples[len(samples) - n:]
    for i in range(n):
        t = i / n
        mixed = body[i] * t + tail[i] * (1.0 - t)
        body[i] = max(-32768, min(32767, int(mixed)))
    return body


def _fade(samples: array.array, rate: int, fade_in_s: float = 0.02, fade_out_s: float = 0.6) -> array.array:
    out = array.array("h", samples)
    a, b = int(rate * fade_in_s), int(rate * fade_out_s)
    for i in range(min(a, len(out))):
        out[i] = int(out[i] * i / a)
    for i in range(min(b, len(out))):
        k = len(out) - 1 - i
        out[k] = int(out[k] * i / b)
    return out


def _wav_bytes(samples: array.array, rate: int) -> bytes:
    buf = io.BytesIO()
    with wave.open(buf, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(samples.tobytes())
    return buf.getvalue()


def prepare_cue(raw_wav: bytes, *, loop: bool) -> bytes:
    """MusicGen's WAV -> the served cue: mono, OUT_RATE, looped or faded out."""
    samples, rate, channels = _read_wav(raw_wav)
    mono = _resample(_to_mono(samples, channels), rate, OUT_RATE)
    shaped = make_loop(mono, OUT_RATE) if loop else _fade(mono, OUT_RATE)
    return _wav_bytes(shaped, OUT_RATE)


# --------------------------------------------------------------------------- generation

def _audio_urls() -> list[str]:
    out: list[str] = []
    for u in (os.getenv("AUDIO_SERVER_URL", "http://audio-server:8082"), os.getenv("ALPACA_AUDIO_URL", "")):
        u = (u or "").rstrip("/")
        if u and u not in out:
            out.append(u)
    return out


def _compose(cue: dict[str, Any]) -> bytes:
    body = json.dumps({"prompt": cue["prompt"], "duration_s": cue["duration_s"], "seed": cue["seed"]}).encode()
    last: Exception | None = None
    for base in _audio_urls():
        req = urllib.request.Request(f"{base}/api/music", data=body, method="POST",
                                     headers={"Content-Type": "application/json"})
        try:
            with urllib.request.urlopen(req, timeout=GENERATE_TIMEOUT_S) as resp:
                data = json.loads(resp.read().decode("utf-8"))
            b64 = data.get("audio_b64") or data.get("audio") or ""
            if not b64:
                raise ValueError("audio server returned no audio")
            return base64.b64decode(b64)
        except Exception as exc:
            last = exc
    raise RuntimeError(f"no audio server could compose it: {last}")


def generate_missing(names: list[str] | None = None) -> dict[str, str]:
    """Compose every cue that has no file yet (or ``names``), one at a time."""
    results: dict[str, str] = {}
    MUSIC_DIR.mkdir(parents=True, exist_ok=True)
    for name in names or list(CUES):
        cue = CUES.get(name)
        if cue is None:
            continue
        path = cue_path(name)
        if names is None and is_current(name):
            continue
        t0 = time.time()
        try:
            wav = prepare_cue(_compose(cue), loop=bool(cue["loop"]))
            tmp = path.with_suffix(".tmp")
            tmp.write_bytes(wav)
            os.replace(tmp, path)
            path.with_suffix(".json").write_text(json.dumps(_recipe(cue)))
            _state["errors"].pop(name, None)
            results[name] = f"composed in {time.time() - t0:.0f}s"
            log.info("[party_music] %s composed in %.0fs", name, time.time() - t0)
        except Exception as exc:
            _state["errors"][name] = str(exc)[:200]
            results[name] = f"failed: {exc}"
            log.warning("[party_music] %s failed: %s", name, exc)
    return results


def ensure_background(names: list[str] | None = None, *, force: bool = False) -> bool:
    """Start composing missing cues in the background; True if a run was started."""
    with _lock:
        t = _state["thread"]
        if t and t.is_alive():
            return False
        if not force and names is None:
            if all(is_current(n) for n in CUES):
                return False
            if time.time() - float(_state["last_attempt"]) < RETRY_AFTER_S:
                return False
        _state["last_attempt"] = time.time()
        t = threading.Thread(target=generate_missing, args=(names,), name="party-music", daemon=True)
        _state["thread"] = t
        t.start()
        return True


def regenerate(names: list[str] | None = None) -> bool:
    """Compose the given cues (default: all) again, replacing the files."""
    return ensure_background(names or list(CUES), force=True)
